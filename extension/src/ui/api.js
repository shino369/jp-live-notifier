/**
 * @param {string} type
 * @param {Record<string, unknown>} [payload]
 */
export async function send(type, payload = {}) {
  const reply = await chrome.runtime.sendMessage({ type, ...payload });
  if (!reply?.ok) throw new Error(reply?.error ?? `no reply to ${type}`);
  return reply.result;
}

export async function load() {
  /** @type {Record<string, any>} */
  const raw = await chrome.storage.local.get(['settings', 'inbox', 'schedule']);
  return {
    settings: normalizeSettings(raw.settings),
    /** @type {import('../lib/inbox.js').InboxState} */
    inbox: { ...emptyInbox(), ...raw.inbox },
    /** @type {import('../lib/schedule.js').ScheduleState} */
    schedule: { ...emptySchedule(), ...raw.schedule },
  };
}

/**
 * @param {() => void} fn called when settings, inbox, or schedule change, or
 *   a poster copy is stored or removed
 */
export function onChange(fn) {
  chrome.storage.onChanged.addListener((changes, area) => {
    if (
      area === 'local' &&
      (changes.inbox ||
        changes.settings ||
        changes.schedule ||
        Object.keys(changes).some((k) => k.startsWith(THUMB_PREFIX)))
    )
      fn();
  });
}

/**
 * An element of the page by id; throws when the page markup lacks it.
 *
 * @param {string} id
 * @returns {HTMLElement}
 */
export function byId(id) {
  const el = document.getElementById(id);
  if (!el) throw new Error(`#${id} is missing from the page`);
  return el;
}

/**
 * Tiny element builder: h('div.row', { onclick }, child, 'text').
 *
 * @param {string} tag `tag.class1.class2`
 * @param {Record<string, any> | null} [props]
 * @param {...(Node | string | null | false | undefined)} children
 * @returns {HTMLElement}
 */
export function h(tag, props, ...children) {
  const [name, ...classes] = tag.split('.');
  const el = document.createElement(name);
  if (classes.length) el.className = classes.join(' ');
  for (const [k, v] of Object.entries(props ?? {})) {
    if (v === undefined || v === null || v === false) continue;
    if (k.startsWith('on')) el.addEventListener(k.slice(2), v);
    else if (k === 'html') el.innerHTML = v;
    else if (k in el && typeof v !== 'string') /** @type {any} */ (el)[k] = v;
    else el.setAttribute(k, v === true ? '' : String(v));
  }
  for (const c of children)
    if (c !== null && c !== undefined && c !== false) el.append(c);
  return el;
}

/**
 * Replace an element's children, skipping null/false entries (plain
 * replaceChildren would print them as text).
 *
 * @param {Element} el
 * @param {Array<Node | string | null | false | undefined>} children
 */
export const fill = (el, children) =>
  el.replaceChildren(
    .../** @type {Array<Node | string>} */ (
      children.filter((c) => c !== null && c !== undefined && c !== false)
    )
  );

